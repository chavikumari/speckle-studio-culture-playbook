"""Bundle the source modules into one classic script for file:// use.

Run from this directory with: python build-static.py
"""

from pathlib import Path
import re


ROOT = Path(__file__).resolve().parent
MODULES = (
    "tool-request.js",
    "reference-art.js",
    "current-art.js",
    "content.js",
    "art.js",
    "guide.js",
    "gift.js",
    "app.js",
)
IMPORT = re.compile(r"^import \{([^}]+)\} from '([^']+)';\s*$", re.MULTILINE)
EXPORT = re.compile(r"^export (?:async )?(?:function|const|let|class) ([A-Za-z_$][\w$]*)", re.MULTILINE)


def bundle_module(filename):
    source = (ROOT / filename).read_text(encoding="utf-8")
    imports = IMPORT.findall(source)
    source = IMPORT.sub("", source)
    exports = EXPORT.findall(source)
    source = re.sub(r"^export ", "", source, flags=re.MULTILINE)
    if re.search(r"^(?:import|export)\s", source, flags=re.MULTILINE):
        raise ValueError(f"Unhandled module syntax in {filename}")
    dependencies = "\n".join(
        f"const {{{names}}} = modules[{dependency!r}];"
        for names, dependency in imports
    )
    result = "{" + ", ".join(exports) + "}"
    return f"modules['./{filename}'] = (function () {{\n{dependencies}\n{source}\nreturn {result};\n}})();"


parts = ["// Generated by build-static.py. Edit the source modules, then rebuild.\n(function () {\n'use strict';\nconst modules = Object.create(null);"]
parts.extend(bundle_module(filename) for filename in MODULES)
parts.append("})();\n")
(ROOT / "site.js").write_text("\n\n".join(parts), encoding="utf-8")
